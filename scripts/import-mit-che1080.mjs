// Generates src/content/mit/che1080-resources.ts from the local MIT OCW mirrors in docs/.
// Only metadata is emitted; no PDF or video is copied. Run: node scripts/import-mit-che1080.mjs
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const COURSES = [
  { dir: '5.111sc-fall-2014', id: '5.111sc', label: '5.111SC' },
  { dir: '5.112-fall-2005', id: '5.112', label: '5.112' },
  { dir: '5.60-spring-2008', id: '5.60', label: '5.60' },
];

const rows = [];
for (const c of COURSES) {
  const root = join('docs', c.dir);
  const meta = JSON.parse(readFileSync(join(root, 'data.json'), 'utf8'));
  const base = `https://ocw.mit.edu/${meta.site_url_path}/`;
  const resRoot = join(root, 'resources');
  for (const slug of readdirSync(resRoot).sort()) {
    const df = join(resRoot, slug, 'data.json');
    if (!existsSync(df)) continue;
    const d = JSON.parse(readFileSync(df, 'utf8'));
    const types = d.learning_resource_types ?? [];
    const yt = d.video_metadata?.youtube_id || d.youtube_id || '';
    let type;
    let lecture;
    let title = d.title ?? '';
    if (types.includes('Lecture Videos') && yt) type = 'video';
    else if (types.includes('Lecture Notes') && d.file_type === 'application/pdf') type = 'lecture-notes';
    else if (c.id === '5.111sc' && types.includes('Problem Set Solutions')) type = 'solution';
    else if (c.id === '5.111sc' && types.includes('Problem Sets')) type = 'exercise';
    else continue;
    if (c.id === '5.60' && type === 'lecture-notes') {
      const m = /^5_60_lecture(\d+)$/.exec(slug);
      if (!m) continue;
      lecture = Number(m[1]);
    } else {
      const m = /Lecture (\d+)/.exec(title);
      if (!m) continue;
      lecture = Number(m[1]);
    }
    if (c.id === '5.111sc' && type === 'exercise' && !/Lecture \d+/.test(title)) continue;
    let localPath;
    let sizeBytes;
    if (type !== 'video' && d.file) {
      const p = join(root, 'static_resources', basename(d.file));
      if (existsSync(p)) {
        localPath = `docs/${c.dir}/static_resources/${basename(d.file)}`;
        sizeBytes = statSync(p).size;
      }
    }
    if (c.id === '5.111sc' && (type === 'exercise' || type === 'solution') && !localPath) continue;
    rows.push({
      id: `mit-${c.id.replace('.', '')}-l${lecture}-${type}${type === 'video' ? '' : ''}`,
      courseId: c.id,
      courseLabel: c.label,
      courseTitle: `${meta.course_title} (${meta.term} ${meta.year})`,
      lectureNumber: lecture,
      title: title.replace(/^Principles of Chemical Science, /, ''),
      type,
      ocwUrl: `${base}resources/${slug}/`,
      ...(type === 'video' ? { youtubeId: yt } : {}),
      ...(localPath ? { localPath, sizeBytes } : {}),
      sourceSlug: slug,
      license: d.license || 'https://creativecommons.org/licenses/by-nc-sa/4.0/',
    });
  }
}

// de-duplicate ids (keep first)
const seen = new Set();
const out = rows.filter(r => (seen.has(r.id) ? false : (seen.add(r.id), true)));
const header = `// GENERATED by scripts/import-mit-che1080.mjs from docs/ MIT OpenCourseWare mirrors. Do not edit by hand.
import type { MitResource } from '../../domain/mit-che1080';

export const MIT_CHE1080_RESOURCES: readonly MitResource[] = `;
mkdirSync('src/content/mit', { recursive: true });
writeFileSync('src/content/mit/che1080-resources.ts', header + JSON.stringify(out, null, 2) + ';\n');
const by = {};
for (const r of out) by[`${r.courseId}:${r.type}`] = (by[`${r.courseId}:${r.type}`] ?? 0) + 1;
console.log(out.length, by);
